"""The `native-runtime` artifact kind, on the release path.

What this file is for
---------------------
`serverosd/` produces a payload nobody could release: `scripts/release.py` had a
closed kind vocabulary of two, and neither of them describes four ELF binaries
and a package manifest. So the payload could be built, verified by hand and
staged by hand, and never promoted by the tool that owns promotion, rollback and
the revision receipt.

These tests are about the seam, not about the package. The package's own rules
are asserted in `serverosd/tests/package_contract.py`; what is asserted here is
that the release path routes a native payload to the right verifier, refuses the
four ways it can be wrong, and — the load-bearing one — **installs nothing**.

Hermetic: a temp runtime root, temp unit and bin directories that are asserted to
stay untouched, and `--no-reload` on every command. Nothing here starts, stops,
enables or reloads a unit. One test replaces `subprocess.run` with a recorder and
proves the native promote calls nothing at all, which is a stronger statement
than "the flag was passed".
"""
import contextlib
import importlib.util
import io
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
RELEASE = ROOT / "scripts" / "release.py"


def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


release = _load("serveros_release_native", RELEASE)
# The payload's own writer and verifier, so a fixture cannot drift from what the
# build actually emits and what the release path actually delegates to.
package_manifest = _load("serveros_native_package_manifest",
                         ROOT / "serverosd" / "package_manifest.py")


def make_native_artifact(base: Path, marker: str, *, mutate=None,
                         extra_files: tuple = (), kinds=("native-runtime",),
                         artifact_manifest: bool = True) -> Path:
    """A native payload, produced by the real writer.

    `PACKAGE.json` is generated by `serverosd/package_manifest.py` rather than
    hand-written, so every digest in it is the digest of the bytes the release
    path will hash. A fixture that invented its own digests would pass while the
    real writer and the real verifier disagreed.
    """
    art = base / f"native-{marker}"
    for name in package_manifest.MEMBERS:
        path = art / "bin" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(f"#!/bin/sh\necho {name} {marker}\n".encode())
        path.chmod(0o755)

    for rel in extra_files:
        target = art / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(b"undeclared\n")

    with contextlib.redirect_stdout(io.StringIO()):
        package_manifest.main(["--out", str(art)])

    if not artifact_manifest:
        (art / package_manifest.ARTIFACT_MANIFEST).unlink()
    elif tuple(kinds) != ("native-runtime",):
        declaration = json.loads((art / package_manifest.ARTIFACT_MANIFEST).read_text())
        declaration["kinds"] = list(kinds)
        (art / package_manifest.ARTIFACT_MANIFEST).write_text(json.dumps(declaration))

    if mutate is not None:
        # AFTER the manifests are written, so a mutation is exactly the thing a
        # verifier has to catch: a payload that changed under its own record.
        mutate(art)
    return art


def run_release(args: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(RELEASE), *args],
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          text=True, env=env)


def rewrite_package(art: Path, change) -> None:
    """Edit `PACKAGE.json` in place. `ARTIFACT.json` does not hash it."""
    path = art / package_manifest.PACKAGE_MANIFEST
    document = json.loads(path.read_text())
    change(document)
    path.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n")


class NativeRuntimeReleaseTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.base = Path(self._tmp.name)
        self.runtime_root = self.base / "runtime-assets"
        self.unit_dir = self.base / "systemd-user"
        self.bin_dir = self.base / "bin"
        self.state_dir = self.base / "state/serveros"
        self.composition = "serveros-native"
        self.comp_root = self.runtime_root / self.composition
        # `--state-dir` is passed explicitly by every command below, but
        # `release.py` evaluates its DEFAULT at parse time, before any option is
        # read, and `runtime/paths.py` refuses an unbound root rather than
        # inventing one. This host binds none, so every subcommand would die in
        # argparse. `DATA_ROOT` is the documented way to name the node's roots,
        # and pointing it at a temp directory keeps the test hermetic.
        self.data_root = self.base / "node"
        self.data_root.mkdir(parents=True, exist_ok=True)
        self.env = {**os.environ, "DATA_ROOT": str(self.data_root)}

    def tearDown(self):
        self._tmp.cleanup()

    def common(self, *extra: str) -> list[str]:
        # `--no-reload` on every invocation. Nothing in this file may ask a
        # service manager for anything, even by accident.
        return ["--runtime-root", str(self.runtime_root),
                "--composition", self.composition,
                "--state-dir", str(self.state_dir),
                "--unit-dir", str(self.unit_dir),
                "--bin-dir", str(self.bin_dir),
                "--no-reload", *extra]

    def promote(self, artifact: Path, revision: str, *extra: str):
        return run_release(["promote", "--artifact", str(artifact),
                            "--revision", revision, *self.common(*extra)],
                           env=self.env)

    def rollback(self, *extra: str):
        return run_release(["rollback", *self.common(*extra)], env=self.env)

    def status(self, *extra: str):
        return run_release(["status", *self.common(*extra)], env=self.env)

    def current(self) -> str | None:
        link = self.comp_root / "current"
        return link.resolve().name if link.is_symlink() else None

    # ---------------------------------------------------------------- GREEN

    def test_a_native_payload_promotes_as_its_own_kind(self):
        art = make_native_artifact(self.base, "one")
        proc = self.promote(art, "rev-1")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn("kind=native-runtime (declared)", proc.stdout)
        self.assertEqual(self.current(), "rev-1")
        receipt = json.loads(
            (self.comp_root / "revisions" / "rev-1" / release.TREE_MANIFEST).read_text())
        self.assertEqual(receipt["kind"], "native-runtime")
        self.assertEqual(receipt["kind_basis"], "declared")

    def test_promoting_a_native_payload_installs_nothing(self):
        art = make_native_artifact(self.base, "one")
        proc = self.promote(art, "rev-1")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        # The whole point of the kind: no unit written, no CLI shim written, no
        # directory created outside the revision root.
        self.assertFalse(self.unit_dir.exists(),
                         f"a native promote created {self.unit_dir}")
        self.assertFalse(self.bin_dir.exists(),
                         f"a native promote created {self.bin_dir}")
        self.assertNotIn("unit", proc.stdout)
        self.assertNotIn("cli shim", proc.stdout)

    def test_promoting_a_native_payload_leaves_an_existing_node_alone(self):
        self.unit_dir.mkdir(parents=True)
        self.bin_dir.mkdir(parents=True)
        unit = self.unit_dir / release.UNIT_NAME
        shim = self.bin_dir / "serverosctl"
        unit.write_text("# untouched sentinel\n")
        shim.write_text("# untouched sentinel\n")

        art = make_native_artifact(self.base, "one")
        self.assertEqual(self.promote(art, "rev-1").returncode, 0)

        self.assertEqual(unit.read_text(), "# untouched sentinel\n")
        self.assertEqual(shim.read_text(), "# untouched sentinel\n")

    def test_a_native_promote_runs_no_subprocess_at_all(self):
        """Not "no reload flag": no process. The flag is a caller's promise."""
        art = make_native_artifact(self.base, "one")
        args = mock.Mock()
        args.runtime_root = self.runtime_root
        args.composition = self.composition
        args.state_dir = self.state_dir
        args.unit_dir = self.unit_dir
        args.bin_dir = self.bin_dir
        args.no_reload = False          # the flag that would allow a reload
        args.dry_run = False
        args.kind = None
        args.artifact = art
        args.revision = "rev-1"

        with mock.patch.object(release.subprocess, "run") as recording, \
                contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(release.cmd_promote(args), 0)
        self.assertFalse(recording.called,
                         f"a native promote ran {recording.call_args_list}")

    def test_previous_is_recorded_and_rollback_restores_it(self):
        first = make_native_artifact(self.base, "one")
        second = make_native_artifact(self.base, "two")
        self.assertEqual(self.promote(first, "rev-1").returncode, 0)
        self.assertEqual(self.promote(second, "rev-2").returncode, 0)
        self.assertEqual(self.current(), "rev-2")

        previous = self.comp_root / "previous"
        self.assertEqual(previous.resolve().name, "rev-1")

        proc = self.rollback()
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn("rolled back    rev-2 -> rev-1", proc.stdout)
        self.assertEqual(self.current(), "rev-1")
        # And the rollback learned the kind from rev-1's own receipt rather than
        # falling back to the default verifier.
        self.assertEqual(previous.resolve().name, "rev-2")
        self.assertFalse(self.unit_dir.exists())

    def test_status_reports_the_native_face_rather_than_divergence(self):
        art = make_native_artifact(self.base, "one")
        self.assertEqual(self.promote(art, "rev-1").returncode, 0)
        proc = self.status()
        self.assertEqual(proc.returncode, 0, proc.stderr + proc.stdout)
        self.assertIn("kind              native-runtime (recorded)", proc.stdout)
        self.assertIn("n/a (native runtime face)", proc.stdout)
        self.assertIn("agreement         AGREE", proc.stdout)

    def test_a_payload_without_a_kind_declaration_is_read_structurally(self):
        """The old fallback still works, and it still needs one answer."""
        art = make_native_artifact(self.base, "one", artifact_manifest=False)
        kind, basis = release.resolve_kind(art)
        self.assertEqual((kind, basis), ("native-runtime", "structural"))

    # ------------------------------------------------------------------ RED

    def test_a_tampered_binary_is_refused(self):
        def tamper(art: Path) -> None:
            target = art / release.NATIVE_ACTUATOR
            target.write_bytes(target.read_bytes() + b"# appended after the fact\n")

        art = make_native_artifact(self.base, "one", mutate=tamper)
        proc = self.promote(art, "rev-1")
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("matches its digest", proc.stderr)
        self.assertIsNone(self.current(), "a refused artifact was promoted anyway")

    def test_a_second_actuator_is_refused(self):
        def promote_a_read_only_row(art: Path) -> None:
            def change(document):
                for row in document["members"]:
                    if row["role"] == "read-only":
                        row["role"] = "actuator"
                        break
            rewrite_package(art, change)

        art = make_native_artifact(self.base, "one", mutate=promote_a_read_only_row)
        proc = self.promote(art, "rev-1")
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("exactly one actuator", proc.stderr)
        self.assertIsNone(self.current())

    def test_a_renamed_actuator_is_refused(self):
        """A self-consistent rename: both fields agree, and that is the point."""
        def rename(art: Path) -> None:
            renamed = art / "bin" / "serverosd"
            renamed.write_bytes((art / release.NATIVE_ACTUATOR).read_bytes())
            renamed.chmod(0o755)

            def change(document):
                for row in document["members"]:
                    if row["role"] == "actuator":
                        row["path"] = "bin/serverosd"
                        row["legacy_path"] = "bin/serverosd"
                        break
            rewrite_package(art, change)

        art = make_native_artifact(self.base, "one", mutate=rename)
        proc = self.promote(art, "rev-1")
        self.assertNotEqual(proc.returncode, 0)
        # Either refusal is the right one: the actuator is not the declared one,
        # and the package no longer carries the member it is required to carry.
        self.assertTrue(
            "the actuator is" in proc.stderr or "every expected member" in proc.stderr,
            proc.stderr)

    def test_a_file_the_package_did_not_declare_is_refused(self):
        art = make_native_artifact(self.base, "one", extra_files=("obj/junk.o",))
        proc = self.promote(art, "rev-1")
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("file present that the package did not declare: obj/junk.o",
                      proc.stderr)
        self.assertIsNone(self.current())

    def test_the_wrong_kind_is_refused(self):
        art = make_native_artifact(self.base, "one")
        proc = self.promote(art, "rev-1", "--kind", "node-runtime")
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("missing bin/serverosd", proc.stderr)
        self.assertIsNone(self.current())

    def test_a_payload_declaring_two_kinds_must_be_narrowed(self):
        art = make_native_artifact(self.base, "one",
                                   kinds=("node-runtime", "native-runtime"))
        proc = self.promote(art, "rev-1")
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("declares more than one kind", proc.stderr)

        narrowed = self.promote(art, "rev-1", "--kind", "native-runtime")
        self.assertEqual(narrowed.returncode, 0, narrowed.stderr)
        self.assertIn("kind=native-runtime (chosen)", narrowed.stdout)

    def test_rollback_refuses_a_tampered_previous_revision(self):
        first = make_native_artifact(self.base, "one")
        second = make_native_artifact(self.base, "two")
        self.assertEqual(self.promote(first, "rev-1").returncode, 0)
        self.assertEqual(self.promote(second, "rev-2").returncode, 0)

        staged = self.comp_root / "revisions" / "rev-1" / release.NATIVE_ACTUATOR
        staged.write_bytes(b"#!/bin/sh\necho swapped\n")

        proc = self.rollback()
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("matches its digest", proc.stderr)
        self.assertEqual(self.current(), "rev-2",
                         "a refused rollback moved `current` anyway")

    # ------------------------------------------------- the other kinds' routing

    def _touch_all(self, root: Path, rels) -> Path:
        for rel in rels:
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("x\n")
        return root

    def test_a_node_shaped_directory_still_resolves_to_node_runtime(self):
        node = self._touch_all(self.base / "node-shaped",
                               release.REQUIRED_MEMBERS[release.NODE_RUNTIME])
        self.assertEqual(release.resolve_kind(node),
                         ("node-runtime", "structural"))

    def test_a_plugin_shaped_directory_still_resolves_to_plugin(self):
        plugin = self._touch_all(self.base / "plugin-shaped",
                                 release.REQUIRED_MEMBERS[release.PLUGIN])
        self.assertEqual(release.resolve_kind(plugin), ("plugin", "structural"))

    def test_a_directory_that_fits_two_kinds_is_refused(self):
        both = self._touch_all(self.base / "both",
                               release.REQUIRED_MEMBERS[release.PLUGIN]
                               + release.REQUIRED_MEMBERS[release.NATIVE_RUNTIME])
        with self.assertRaises(SystemExit) as caught:
            release.resolve_kind(both)
        self.assertIn("cannot tell what kind of artifact this is",
                      str(caught.exception))

    def test_the_existing_kinds_are_unchanged(self):
        self.assertEqual(release.ARTIFACT_KINDS,
                         ("node-runtime", "plugin", "native-runtime"))
        self.assertEqual(
            release.REQUIRED_MEMBERS[release.NODE_RUNTIME],
            ("bin/serverosd", "bin/serverosctl", "runtime/daemon.py",
             "runtime/cli.py", "runtime/serverosd.service",
             "workengine/schema.sql"))
        self.assertEqual(release.REQUIRED_MEMBERS[release.PLUGIN],
                         (".claude-plugin/plugin.json", ".codex-plugin/plugin.json"))
        self.assertEqual(release.REQUIRED_MEMBERS[release.NATIVE_RUNTIME],
                         ("PACKAGE.json", "bin/serveros-native-core"))


if __name__ == "__main__":
    unittest.main()
