"""The committed Claude Code plugin is the one its source generates.

`plugins/serveros-fleet-ingress/` (retired) is generated by
`scripts/fleet_plugin.py build` and committed; the root marketplace file now
belongs to `distribution/build.py` and lists `serveros-fleet`. A Skill edited in the shared
source without a rebuild would ship the old text; this test refuses that.
"""
from __future__ import annotations

import importlib.util
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("fleet_plugin_tool", ROOT / "scripts" / "fleet_plugin.py")
fleet_plugin = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = fleet_plugin
_spec.loader.exec_module(fleet_plugin)


class TheCommittedPluginIsCurrent(unittest.TestCase):
    def test_the_committed_tree_matches_a_fresh_build(self) -> None:
        self.assertEqual(fleet_plugin.differences(fleet_plugin.DEFAULT_NEXT_MCP_URL), [],
                         "run `python3 scripts/fleet_plugin.py build` and commit the result")

    def test_the_root_marketplace_no_longer_offers_the_retired_plugin(self) -> None:
        """The root is the `serveros-fleet` marketplace now (distribution/build.py)."""
        market = json.loads(fleet_plugin.MARKETPLACE_FILE.read_text(encoding="utf-8"))
        self.assertEqual(market["name"], fleet_plugin.SIDE_MARKETPLACE_NAME)
        self.assertNotIn(fleet_plugin.PLUGIN_NAME, [p["name"] for p in market["plugins"]])

    def test_install_of_the_retired_plugin_points_at_the_new_installer(self) -> None:
        self.assertEqual(fleet_plugin.install(fleet_plugin.DEFAULT_NEXT_MCP_URL, False), 2)

    def test_the_committed_binding_requests_all_six_scopes(self) -> None:
        binding = json.loads((fleet_plugin.PLUGIN_DIR / ".mcp.json").read_text(encoding="utf-8"))
        scopes = binding["mcpServers"]["serveros-fleet"]["oauth"]["scopes"].split()
        self.assertEqual(len(scopes), 6, scopes)

    def test_a_stale_skill_is_detected(self) -> None:
        skill = fleet_plugin.PLUGIN_DIR / "skills" / "fleet-evidence-review" / "SKILL.md"
        original = skill.read_bytes()
        try:
            skill.write_bytes(original + b"\nstale\n")
            self.assertIn("plugins/serveros-fleet-ingress/skills/fleet-evidence-review/SKILL.md",
                          fleet_plugin.differences(fleet_plugin.DEFAULT_NEXT_MCP_URL))
        finally:
            skill.write_bytes(original)


if __name__ == "__main__":
    unittest.main()
