#!/usr/bin/env python3
"""Package the Fleet Next cloud-facing plugin folder into one deterministic ZIP.

Why this exists
---------------
A ChatGPT plugin is updated in place from a ZIP. Two builds of the same source
that produce different bytes are two releases, so an operator cannot tell a
rebuild from a change, and `update_plugin`'s guarded "expected release id"
becomes the only thing standing between a routine rebuild and a silent
replacement. This script is the one place that turns a source tree into the
archive, so the recipe is written down once instead of being re-derived by
whoever happens to run `zip` that day.

Two digests, because they answer two different questions
--------------------------------------------------------
`content_sha256` hashes the *relative path + bytes* of every packaged file in
sorted order. That is the same recipe `tests/test_plugin_composition.py` uses
on the Native artifact, and it is stable across machines, Python builds and
zlib versions — it is the identity of the SOURCE.

`archive_sha256` hashes the ZIP bytes themselves. It is what a client sees and
what a release record quotes, but it is only reproducible on a fixed
toolchain: the deflate stream depends on the zlib the interpreter was linked
against. So this script asserts archive stability within one run (`--check`)
and prints the content digest alongside it, and it never claims the archive
digest is portable. When the two must be compared across machines, compare the
content digest.

What this package must NOT be
-----------------------------
Issue #186 separates this release from the Native ServerOS plugin composition
at `plugin/bundle.yaml`. That composition ships a node runtime, MCP servers and
executable entry points; this one is instruction-only. So the build refuses to
package a tree that declares a live MCP surface — a `.app.json`, a `.mcp.json`
or a `mcp.json` anywhere, or an `extensions` block asking for one. The refusal
is the point: a packaging bug here would put an unreviewed network surface in
front of a client under a manifest that says "instruction-only".

What ships, and why the member set is a declaration
---------------------------------------------------
The archive contains exactly `plugin.json`, `icon.svg`, `README.md` and
everything under `skills/` — `PAYLOAD_ENTRIES`, written down rather than
derived. The tempting alternative is "package the folder", and it fails in a
way that is easy to miss: the first build writes `dist/`, the second build finds
it and packages the previous archive inside the new one, so the digest changes
on every run and stops being a release identity. Bytecode caches get picked up
the same way. `--check` would not notice, because it builds into a scratch
directory where none of that exists yet — a green check on a broken claim.
Naming the members makes the archive a function of the source alone.

Usage
-----
    python3 build_zip.py                 # package the directory this file is in
    python3 build_zip.py PATH --out DIR  # package elsewhere
    python3 build_zip.py --check         # build twice, assert both digests match
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path

#: Names that would declare a live MCP/App surface. Their presence makes this
#: artifact something other than instruction-only, which is a different review.
LIVE_SURFACE_NAMES = frozenset({".app.json", ".mcp.json", "mcp.json"})

#: The payload, named exhaustively. The archive is what a client loads, so the
#: member set is a DECLARATION, not a consequence of what happens to be on disk.
#: `scripts/build.py` applies the same rule to its own output ("the output
#: directory is generated-only") and for the same reason: a builder that
#: packages whatever it finds will eventually package its own previous output.
#: Everything else in this directory — this script, the package notes, a `dist/`
#: from an earlier run, `__pycache__` — is source-side and stays out.
PAYLOAD_ENTRIES = ("plugin.json", "icon.svg", "README.md", "skills")

#: Generated by-products, named so a refusal can say which one it saw. This
#: guards the RULE above rather than the tree: the selection below cannot reach
#: these today, and this is what keeps that true if the rule is ever widened.
BYPRODUCT_PARTS = frozenset({"dist", "out", "__pycache__"})

#: Every top-level property the 1.0.0 manifest schema defines. `additionalProperties`
#: is false at the root, so a manifest carrying anything else is refused by a
#: conforming client; this build refuses it first, where the message can say which
#: key is stray. Read from the schema at
#: https://agent-plugins.org/schemas/1.0.0/plugin.schema.json
SCHEMA_PROPERTIES = frozenset({
    "$schema", "name", "version", "description", "author", "homepage",
    "repository", "license", "keywords", "extensions",
})

SCHEMA_URL = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"

#: A fixed timestamp, not "now". A build that stamps the wall clock produces a
#: different archive every second and cannot be verified by rebuilding.
FIXED_DATE_TIME = (1980, 1, 1, 0, 0, 0)

#: Mirrors `--mode 0644` on every member, so a file's local permissions cannot
#: leak into the archive.
FIXED_MODE = 0o644 << 16

NAME_RE = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
SEMVER_RE = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+")


class Refused(Exception):
    """The tree is not packageable. Carries the reason, not a traceback."""


def load_manifest(root: Path) -> dict:
    path = root / "plugin.json"
    if not path.is_file():
        raise Refused(f"no plugin.json in {root}")
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise Refused(f"plugin.json is not JSON: {exc}") from exc
    if not isinstance(manifest, dict):
        raise Refused("plugin.json is not an object")

    stray = sorted(set(manifest) - SCHEMA_PROPERTIES)
    if stray:
        raise Refused(
            f"plugin.json declares {stray}, which the 1.0.0 manifest schema does "
            f"not define and forbids (additionalProperties: false). Client-specific "
            f"data belongs under `extensions`."
        )
    if manifest.get("$schema") != SCHEMA_URL:
        raise Refused(f"plugin.json $schema must be {SCHEMA_URL!r}")

    name = manifest.get("name", "")
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise Refused(f"plugin name {name!r} is not a lowercase hyphenated token")
    version = manifest.get("version", "")
    if not isinstance(version, str) or not SEMVER_RE.fullmatch(version):
        raise Refused(f"plugin version {version!r} is not MAJOR.MINOR.PATCH")
    return manifest


def audit(root: Path) -> None:
    """Refuse what is wrong wherever it sits in the source tree.

    These run over the WHOLE tree rather than over the selection below. A member
    allowlist cannot see a file it did not select, so checking only the selection
    makes the refusal vacuous: a `mcp.json` that was meant to declare a connector
    would be dropped in silence, and the package would look exactly the same
    whether the declaration was refused or merely ignored. The presence is the
    offence; its absence from the archive is not a substitute for saying so.
    """
    symlinks = sorted(p.relative_to(root).as_posix()
                      for p in root.rglob("*") if p.is_symlink())
    if symlinks:
        # A symlink's target is not in the archive, so the archive would unpack
        # into something that was never reviewed — and on Windows it would not
        # unpack at all.
        raise Refused(f"refusing to package symlinks: {symlinks}")

    live = sorted(p.relative_to(root).as_posix() for p in root.rglob("*")
                  if p.is_file() and p.name in LIVE_SURFACE_NAMES)
    if live:
        raise Refused(
            f"refusing to package a live MCP/App surface ({live}). This release is "
            f"instruction-only; a connector surface is a separate review (#186)."
        )
    declared = manifest_live_surface(root)
    if declared:
        raise Refused(f"plugin.json declares a live MCP surface: {declared}")


def collect(root: Path) -> list[Path]:
    """The payload members, or a refusal naming the one that disqualifies it."""
    audit(root)

    selected: list[Path] = []
    for entry in PAYLOAD_ENTRIES:
        path = root / entry
        if path.is_file():
            selected.append(path)
        elif path.is_dir():
            selected.extend(p for p in path.rglob("*") if p.is_file())

    if not any(p.name == "SKILL.md" for p in selected):
        raise Refused("no skills/<name>/SKILL.md: an instruction-only plugin with "
                      "no instructions is not a plugin")

    byproduct = sorted(p.relative_to(root).as_posix() for p in selected
                       if set(p.relative_to(root).parts) & BYPRODUCT_PARTS
                       or p.suffix in (".pyc", ".pyo"))
    if byproduct:
        raise Refused(f"a generated by-product reached the payload: {byproduct}")
    return selected


def manifest_live_surface(root: Path) -> str | None:
    """Whether plugin.json itself asks for a live surface, and which key."

    Read from the raw file rather than the parsed manifest so a build refusal
    never depends on how a later parser chose to normalize a missing section.
    """
    try:
        manifest = json.loads((root / "plugin.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(manifest, dict):
        return None
    for key in ("mcpServers", "mcp_servers", "app"):
        if key in manifest:
            return key
    extensions = manifest.get("extensions")
    if isinstance(extensions, dict):
        for namespace, block in extensions.items():
            if isinstance(block, dict) and block.get("declaresMcpServer"):
                return f"extensions.{namespace}.declaresMcpServer"
    return None


def content_digest(root: Path, rels: list[str]) -> str:
    """One digest over relative path + bytes, sorted. Toolchain-independent."""
    accumulator = hashlib.sha256()
    for rel in sorted(rels):
        accumulator.update(rel.encode())
        accumulator.update((root / rel).read_bytes())
    return accumulator.hexdigest()


def write_archive(root: Path, files: list[Path], destination: Path) -> str:
    """Write the ZIP and return its sha256. Same inputs, same bytes."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path in sorted(files, key=lambda p: p.relative_to(root).as_posix()):
            rel = path.relative_to(root).as_posix()
            info = zipfile.ZipInfo(rel, date_time=FIXED_DATE_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = FIXED_MODE
            zf.writestr(info, path.read_bytes(),
                        compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    return hashlib.sha256(destination.read_bytes()).hexdigest()


def build(root: Path, out_dir: Path) -> dict:
    manifest = load_manifest(root)
    files = collect(root)
    name, version = manifest["name"], manifest["version"]
    rels = [p.relative_to(root).as_posix() for p in files]

    archive = out_dir / f"{name}-v{version}.zip"
    archive_sha = write_archive(root, files, archive)
    content_sha = content_digest(root, rels)
    (archive.parent / f"{archive.name}.sha256").write_text(
        f"{archive_sha}  {archive.name}\n", encoding="utf-8")
    return {
        "archive": str(archive),
        "archive_sha256": archive_sha,
        "content_sha256": content_sha,
        "members": sorted(rels),
        "name": name,
        "version": version,
    }


def check(root: Path) -> dict:
    """Build twice into separate directories and assert both digests agree.

    This is the reproducibility claim made mechanical. It proves stability
    within one toolchain; it does not prove the archive digest is portable,
    which is why the content digest is compared too and reported separately.
    """
    import tempfile
    with tempfile.TemporaryDirectory() as one, tempfile.TemporaryDirectory() as two:
        first = build(root, Path(one))
        second = build(root, Path(two))
    if first["archive_sha256"] != second["archive_sha256"]:
        raise Refused(
            "two builds of one tree produced different archive bytes "
            f"({first['archive_sha256']} vs {second['archive_sha256']}); the "
            "packaging recipe is not deterministic"
        )
    if first["content_sha256"] != second["content_sha256"]:
        raise Refused("two builds of one tree produced different content digests")
    first["stable"] = True
    return first


def main(argv: list[str] | None = None) -> int:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("plugin_dir", nargs="?", default=str(here),
                        help="plugin folder holding plugin.json (default: this directory)")
    parser.add_argument("--out", default="dist", help="archive destination (default: dist)")
    parser.add_argument("--check", action="store_true",
                        help="build twice and assert both digests match")
    args = parser.parse_args(argv)

    root = Path(args.plugin_dir).resolve()
    try:
        result = check(root) if args.check else build(root, Path(args.out).resolve())
    except Refused as refusal:
        print(f"REFUSED: {refusal}", file=sys.stderr)
        return 2

    if args.check:
        print(f"OK stable: {result['name']} v{result['version']} "
              f"({len(result['members'])} files) archive_sha256={result['archive_sha256']}")
    else:
        print(f"{result['archive']} sha256={result['archive_sha256']}")
    print(f"content_sha256={result['content_sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
