#!/usr/bin/env python3
"""Build a **TEST FIXTURE** Claude Code plugin over the local stdio surface.

This is deliberately a second builder, not a mode of
`build_cc_plugin.py`. That builder produces the development adapter that binds
the real Fleet Next ingress over HTTPS with OAuth scopes; its tests assert the
binding is never a local command or an environment block, because a command
would silently turn the release-shaped adapter into a stdio server. Loosening
that builder to make a test possible would remove the assertion that keeps the
two artefacts apart.

So the artefacts stay apart:

| | `build_cc_plugin.py` | this file |
|---|---|---|
| binding | `type: http` to an observed `/mcp` URL | `type: stdio` to a local script |
| credential | OAuth scope subset, consented by the owner | none — a fixture principal |
| device | the real fleet through the real ingress | `device:fixture-node`, invented |
| distribution | DEVELOPMENT_ONLY, loaded in place | TEST_FIXTURE, loaded in place |
| may be installed | no | no |

What it shares with the development adapter is the one thing that must not
fork: the shared `SKILL.md` files are read from
`integrations/fleet-v1-first-install/plugin/skills/` and written byte for byte.
A test asserts that identity.

The generated `.mcp.json` names the fixture server, a wire log and a state
directory. The server is `fixture_stdio_server.py`, which imports the real
`fleet_mcp` dispatcher and tools from the repository. Nothing in the generated
directory is a credential, and the only process the binding starts is that
script, under the Python that built the fixture.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

# A builder run must not leave `__pycache__` in a source tree that records
# hashes for installed artifacts. The fixture server sets the same flag for
# itself; this covers the builder process before it loads the shared modules.
sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SHARED_SKILLS = ROOT / "fleet-v1-first-install" / "plugin" / "skills"
DEFAULT_SERVER = HERE / "fixture_stdio_server.py"

_spec = importlib.util.spec_from_file_location(
    "fleet_cc_dev_plugin_for_fixture", HERE / "build_cc_plugin.py")
cc = importlib.util.module_from_spec(_spec)
sys.modules["fleet_cc_dev_plugin_for_fixture"] = cc
_spec.loader.exec_module(cc)

FIXTURE_NAME = "serveros-fleet-dev-fixture"
FIXTURE_DISPLAY_NAME = "ServerOS Fleet (local test fixture)"
FIXTURE_VERSION = "0.0.1"
FIXTURE_MARKER = "TEST_FIXTURE_ONLY.md"
SERVER_NAME = "serveros-fleet-fixture"
SERVED_TOOL_COUNT = 34

MARKER_BODY = """# TEST FIXTURE ONLY — not the release, not the development adapter

This directory was generated by
`integrations/fleet-cc-dev-plugin/build_local_fixture.py`. It loads the MCP
surface of `fixture_stdio_server.py` into a real Claude Code client so that
`initialize`, `tools/list` and scoped read-only `tools/call` can be observed.

| | this fixture | the development adapter | the release |
|---|---|---|---|
| transport | local **stdio**, one process | HTTPS to the Fleet Next ingress | HTTPS, installed |
| device | `device:fixture-node`, invented | the real fleet | the real fleet |
| credential | none; a fixture principal holds `fleet:read` | OAuth request for `fleet:read` | owner consent |
| installable | **no** | no | yes, when the release gates pass |

Rules:

- **Do not install this** into a global or production client, and do not copy
  it to another user.
- It is not a statement that the Fleet ingress works. It never opens a socket
  and never contacts a device.
- The shared Skills are the canonical bytes from
  `integrations/fleet-v1-first-install/plugin/skills/`; this builder does not
  re-type them.
- Every server answer that could be mistaken for a real observation carries
  `TEST_FIXTURE` in its detail, source or title.
"""


class FixtureRefused(cc.Refused):
    """Same refusal type as the shared builder, with fixture-specific text."""


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check_paths(out: Path) -> None:
    out = Path(out).resolve()
    source = SHARED_SKILLS.resolve()
    if out == source or source in out.parents:
        raise FixtureRefused(
            cc.SOURCE_REFUSED,
            f"--out {out} is the Skills source, or is inside it. The generated "
            f"fixture would contain the directory it was generated from.")
    if out in source.parents:
        raise FixtureRefused(
            cc.SOURCE_REFUSED,
            f"--out {out} contains the Skills source {source}.")
    if out.exists():
        raise FixtureRefused(
            cc.SOURCE_REFUSED,
            f"--out {out} already exists. A second generation would blend into "
            f"the first; remove it deliberately or choose another directory.")


def manifest() -> dict:
    """The documented `.claude-plugin/plugin.json` shape, for a fixture."""
    return {
        "$schema": "https://code.claude.com/schemas/plugin.json",
        "name": FIXTURE_NAME,
        "displayName": FIXTURE_DISPLAY_NAME,
        "version": FIXTURE_VERSION,
        "description": (
            "TEST FIXTURE ONLY — a local stdio Fleet surface for Claude Code "
            "client tests. No device, no network, no credential, and not the "
            "release or the development adapter."
        ),
        "author": {"name": "ProfessorZhi"},
        "license": "MIT",
        "homepage": "https://github.com/ProfessorZhi/serveros",
        "repository": "https://github.com/ProfessorZhi/serveros",
        "keywords": ["serveros", "fleet", "mcp", "test-fixture"],
    }


def mcp_config(server: Path, state_dir: Path, log_path: Path,
               principal: str) -> dict:
    """The stdio binding. A command here is the point, and is fixture-only.

    `type: stdio` is written explicitly. Claude Code reads an entry with a
    `command` and no `type` as stdio, but spelling it removes the reader's need
    to know that fallback, and the development adapter's tests can keep
    asserting that *its* binding never carries one.
    """
    if principal not in ("read-only", "owner"):
        raise FixtureRefused(cc.SOURCE_REFUSED,
                             f"principal must be read-only or owner, not {principal!r}")
    return {
        "mcpServers": {
            SERVER_NAME: {
                "type": "stdio",
                "command": sys.executable,
                "args": [
                    str(server),
                    "--log", str(log_path),
                    "--state-dir", str(state_dir),
                    "--principal", principal,
                ],
                "env": {"PYTHONDONTWRITEBYTECODE": "1"},
            }
        }
    }


def generate(*, out: Path, skills_source: Path = SHARED_SKILLS,
             server: Path = DEFAULT_SERVER, principal: str = "read-only") -> dict:
    out = Path(out)
    check_paths(out)
    server = Path(server).resolve()
    if not server.is_file():
        raise FixtureRefused(cc.SOURCE_REFUSED, f"no fixture server at {server}")

    skills = cc.read_skills(Path(skills_source))
    for name, body in skills:
        cc.check_skill_front_matter(name, body)

    out.mkdir(parents=True)
    (out / ".claude-plugin").mkdir()
    (out / ".claude-plugin" / "plugin.json").write_text(
        json.dumps(manifest(), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")

    state_dir = out / ".fixture-state"
    log_path = state_dir / "mcp-wire.log"
    (out / ".mcp.json").write_text(
        json.dumps(mcp_config(server, state_dir, log_path, principal),
                   indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")

    for name, body in skills:
        target = out / "skills" / name
        target.mkdir(parents=True)
        (target / "SKILL.md").write_text(body, encoding="utf-8")

    (out / FIXTURE_MARKER).write_text(MARKER_BODY, encoding="utf-8")
    return {
        "status": "TEST_FIXTURE_READY",
        "out": str(out),
        "name": FIXTURE_NAME,
        "mcp_server": SERVER_NAME,
        "principal": principal,
        "skills": [name for name, _ in skills],
        "skills_sha256": {name: _sha256(out / "skills" / name / "SKILL.md")
                          for name, _ in skills},
        "served_tool_count": SERVED_TOOL_COUNT,
        "server": str(server),
        "test_only": True,
        "installable": False,
        "creates_plugin": False,
        "uploads": [],
        "installs": [],
        "distribution": "TEST_FIXTURE_ONLY_NOT_A_RELEASE",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--skills-source", type=Path, default=SHARED_SKILLS)
    parser.add_argument("--server", type=Path, default=DEFAULT_SERVER)
    parser.add_argument("--principal", choices=("read-only", "owner"),
                        default="read-only")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    try:
        record = generate(out=args.out, skills_source=args.skills_source,
                          server=args.server, principal=args.principal)
    except cc.Refused as exc:
        sys.stderr.write(f"fixture-refused: {exc.code}: {exc.detail}\n")
        return 2
    if args.json:
        sys.stdout.write(json.dumps(record, indent=2) + "\n")
    else:
        sys.stdout.write(
            f"TEST_FIXTURE_READY {record['out']}\n"
            f"  skills        {len(record['skills'])}\n"
            f"  mcp server    {record['mcp_server']} (stdio)\n"
            f"  principal     {record['principal']}\n"
            f"  installable   {record['installable']}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
