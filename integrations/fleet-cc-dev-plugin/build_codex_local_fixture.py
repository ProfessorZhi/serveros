#!/usr/bin/env python3
"""Build a local Codex marketplace + stdio fixture for an isolated handshake.

This is a test fixture, not the release and not the remote adapter:

* the plugin carries the shared Fleet Skills byte for byte;
* its MCP entry is stdio to `fixture_stdio_server.py`, with an explicit wire log
  and state directory under the fixture output;
* a local `.agents/plugins/marketplace.json` points at the plugin so
  `codex plugin marketplace add` can install it into a fresh `CODEX_HOME`.

Nothing here writes the user's global `~/.codex`, reads a credential or opens a
network socket. The real CLI runner (`run_codex_client_e2e.py`) is what starts
Codex and performs the handshake.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REPO = ROOT.parent
SHARED = ROOT / "fleet-v1-first-install" / "plugin" / "skills"
FIXTURE_SERVER = HERE / "fixture_stdio_server.py"

_spec = importlib.util.spec_from_file_location("fleet_codex_fixture_shared", HERE / "build_cc_plugin.py")
_cc = importlib.util.module_from_spec(_spec)
sys.modules["fleet_codex_fixture_shared"] = _cc
_spec.loader.exec_module(_cc)

Refused = _cc.Refused
SOURCE_REFUSED = _cc.SOURCE_REFUSED

FIXTURE_NAME = "serveros-fleet-codex-fixture"
SERVER_NAME = "serveros-fleet"
MARKET_NAME = "serveros-fleet-codex-fixture-market"
DISPLAY_NAME = "ServerOS Fleet (Codex local fixture)"
FIXTURE_VERSION = "0.0.1"
MARKER = "TEST_FIXTURE_ONLY.md"
OWNED_NAME = "serveros-fleet-codex-owned"
OWNED_MARKET = "serveros-fleet-codex-owned-market"


def generate(*, out: Path, skills_source: Path = SHARED) -> dict:
    out = Path(out).resolve()
    if out.exists():
        raise Refused(SOURCE_REFUSED,
                      f"{out} already exists; the fixture is generated once into "
                      f"an empty directory")
    source = _cc.check_skills_source(skills_source)
    _cc.check_paths(source, out)
    skills = _cc.read_skills(source)
    for name, body in skills:
        _cc.check_skill_front_matter(name, body)

    plugin = out / "plugin"
    plugin_manifest = {
        "name": FIXTURE_NAME,
        "version": FIXTURE_VERSION,
        "description": "TEST FIXTURE ONLY — local Codex stdio Fleet surface.",
        "author": {"name": "ProfessorZhi"},
        "license": "MIT",
        "skills": "./skills/",
        "mcpServers": "./.codex-mcp.json",
        "interface": {
            "displayName": DISPLAY_NAME,
            "shortDescription": "Local no-model Codex handshake fixture.",
            "longDescription": (
                "Loads the shared Fleet Skills and a stdio MCP fixture. It is not "
                "the release, not a real device and not a remote ingress."
            ),
            "developerName": "ProfessorZhi",
            "category": "Productivity",
        },
    }
    state = out / "state"
    state.mkdir(parents=True)
    (plugin / ".codex-plugin").mkdir(parents=True)
    (plugin / "skills").mkdir()
    (plugin / ".codex-plugin" / "plugin.json").write_text(
        json.dumps(plugin_manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")
    binding = {
        "mcpServers": {
            SERVER_NAME: {
                "command": sys.executable,
                "args": [
                    str(FIXTURE_SERVER),
                    "--log", str(state / "wire.jsonl"),
                    "--state-dir", str(state / "state"),
                ],
                "cwd": str(REPO),
                "env": {"PYTHONDONTWRITEBYTECODE": "1"},
            }
        }
    }
    (plugin / ".codex-mcp.json").write_text(
        json.dumps(binding, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for name, body in skills:
        dest = plugin / "skills" / name / "SKILL.md"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(body, encoding="utf-8")
    (plugin / MARKER).write_text(
        "# TEST FIXTURE ONLY\n\n"
        "Generated by `build_codex_local_fixture.py`. Do not install globally; "
        "install it into an isolated CODEX_HOME only.\n", encoding="utf-8")

    marketplace = {
        "name": MARKET_NAME,
        "description": "Local Codex fixture marketplace for ServerOS Fleet.",
        "interface": {"displayName": "ServerOS Fleet Codex Fixture"},
        "plugins": [{
            "name": FIXTURE_NAME,
            "source": {"source": "local", "path": "./plugin"},
            "policy": {"installation": "AVAILABLE", "authentication": "ON_USE"},
            "category": "Productivity",
        }],
    }
    market_dir = out / ".agents" / "plugins"
    market_dir.mkdir(parents=True)
    (market_dir / "marketplace.json").write_text(
        json.dumps(marketplace, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")

    members = sorted(
        p.relative_to(plugin).as_posix()
        for p in plugin.rglob("*") if p.is_file()
    )
    return {
        "schema": "serveros/fleet-codex-fixture.v1",
        "distribution": "TEST_FIXTURE_ONLY_NOT_A_RELEASE",
        "installable": False,
        "fixture_name": FIXTURE_NAME,
        "marketplace_name": MARKET_NAME,
        "server_name": SERVER_NAME,
        "plugin": str(plugin),
        "marketplace": str(out),
        "marketplace_manifest": str(market_dir / "marketplace.json"),
        "skills": [name for name, _ in skills],
        "members": members,
        "member_sha256": {
            member: hashlib.sha256((plugin / member).read_bytes()).hexdigest()
            for member in members
        },
        "writes": [],
        "uploads": [],
        "installs": [],
        "global_config_written": False,
        "real_device": False,
    }


def generate_owned(*, out: Path, entry: Path, config: Path, state_dir: Path,
                   cwd: Path, skills_source: Path = SHARED) -> dict:
    """Build a Codex plugin that binds the real owned stdio runtime.

    This is not a fixture provider: the MCP command is the real
    `bin/serveros-fleet-owned --stdio --config PATH`, and its environment points
    at the existing ServerOS state root. It writes no global config and reads
    no credential.
    """
    out = Path(out).resolve()
    if out.exists():
        raise Refused(SOURCE_REFUSED,
                      f"{out} already exists; the owned fixture is generated once")
    entry_s, config_s = _cc.check_owned_entry(str(entry), str(config))
    state_dir = Path(state_dir).resolve()
    if not state_dir.is_dir():
        raise Refused(SOURCE_REFUSED, f"state dir is not a directory: {state_dir}")
    source = _cc.check_skills_source(skills_source)
    _cc.check_paths(source, out)
    skills = _cc.read_skills(source)
    for name, body in skills:
        _cc.check_skill_front_matter(name, body)
    plugin = out / "plugin"
    (plugin / ".codex-plugin").mkdir(parents=True)
    (plugin / "skills").mkdir()
    manifest = {
        "name": OWNED_NAME,
        "version": FIXTURE_VERSION,
        "description": "REAL OWNED STDIO — local ServerOS Fleet runtime, no fixture provider.",
        "author": {"name": "ProfessorZhi"},
        "license": "MIT",
        "skills": "./skills/",
        "mcpServers": "./.codex-mcp.json",
        "interface": {
            "displayName": "ServerOS Fleet (Codex owned stdio)",
            "shortDescription": "Real local owner runtime for Codex.",
            "longDescription": "Binds the existing ServerOS Fleet owned stdio runtime.",
            "developerName": "ProfessorZhi",
            "category": "Productivity",
        },
    }
    (plugin / ".codex-plugin" / "plugin.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    binding = {"mcpServers": {SERVER_NAME: {
        "command": entry_s,
        "args": ["--stdio", "--config", config_s],
        "cwd": str(Path(cwd).resolve()),
        "env": {"SERVEROS_STATE_DIR": str(state_dir),
                "PYTHONDONTWRITEBYTECODE": "1"},
    }}}
    (plugin / ".codex-mcp.json").write_text(
        json.dumps(binding, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for name, body in skills:
        dest = plugin / "skills" / name / "SKILL.md"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(body, encoding="utf-8")
    market_dir = out / ".agents" / "plugins"
    market_dir.mkdir(parents=True)
    marketplace = {
        "name": OWNED_MARKET,
        "description": "Local marketplace for the real ServerOS Fleet Codex adapter.",
        "interface": {"displayName": "ServerOS Fleet Codex Owned"},
        "plugins": [{
            "name": OWNED_NAME,
            "source": {"source": "local", "path": "./plugin"},
            "policy": {"installation": "AVAILABLE", "authentication": "ON_USE"},
            "category": "Productivity",
        }],
    }
    (market_dir / "marketplace.json").write_text(
        json.dumps(marketplace, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    members = sorted(p.relative_to(plugin).as_posix()
                     for p in plugin.rglob("*") if p.is_file())
    return {
        "schema": "serveros/fleet-codex-owned-fixture.v1",
        "mode": "OWNED_STDIO",
        "distribution": "LOCAL_REAL_OWNED_RUNTIME",
        "installable": False,
        "real_owned_entry": True,
        "fixture_device": False,
        "fixture_name": OWNED_NAME,
        "marketplace_name": OWNED_MARKET,
        "server_name": SERVER_NAME,
        "entry": entry_s,
        "config": config_s,
        "state_dir": str(state_dir),
        "plugin": str(plugin),
        "marketplace": str(out),
        "marketplace_manifest": str(market_dir / "marketplace.json"),
        "skills": [name for name, _ in skills],
        "members": members,
        "member_sha256": {m: hashlib.sha256((plugin / m).read_bytes()).hexdigest()
                          for m in members},
        "writes": [], "uploads": [], "installs": [],
        "global_config_written": False,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--skills-source", default=str(SHARED))
    args = parser.parse_args(argv)
    try:
        record = generate(out=Path(args.out), skills_source=Path(args.skills_source))
    except Refused as refusal:
        print(f"{refusal.code}: {refusal.detail}", file=sys.stderr)
        return 2
    print(f"TEST_FIXTURE_READY {record['plugin']}")
    print(f"marketplace={record['marketplace']} skills={len(record['skills'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
